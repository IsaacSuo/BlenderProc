def _load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Failed to load module from {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_HERE = Path(__file__).resolve().parent
render_mod = _load_module("front3d_place_and_render", _HERE / "front3d_place_and_render.py")
render_profile = render_mod.render_profile
lamp_lighting = _load_module("lamp_lighting", _HERE / "lamp_lighting.py")


